from sklearn.preprocessing import StandardScaler

numeric_cols = ["BHK", "Bathrooms", "Log_Super_Area", "Log_Carpet_Area",
                "Floor_Number", "Total_Floors", "Age_of_Property",
                "Distance_to_Metro_km", "Distance_to_City_Center_km"]

scaler = StandardScaler()
X_train_final[numeric_cols] = scaler.fit_transform(X_train_final[numeric_cols])
X_test_final[numeric_cols]  = scaler.transform(X_test_final[numeric_cols])

print(X_train_final.columns.tolist())

y_train_log = np.log1p(y_train)
y_test_log  = np.log1p(y_test)

# Gradient Decent

X = np.asarray(X_train_final, dtype=float)
y = np.asarray(y_train_log, dtype=float)

n, d = X.shape # n = number of rows ; d = number of features
w = np.zeros(d)   # making the initial weights 0
b = 0.0         # bias/intercept (c)
lr = 0.1
n_iters = 1000
loss_history = []

for i in range(n_iters):
    y_pred = X @ w + b      # Prediction = features × weights + bias ; "@" means matrix multiplication

    error = y_pred - y      # calculating the error

    loss = np.mean(error ** 2)  # MSE
    loss_history.append(loss)

    grad_w = (2 / n) * (X.T @ error)  # derivative of MSE's formula
    grad_b = (2 / n) * np.sum(error)

    w -= lr * grad_w
    b -= lr * grad_b

print("Final loss:", loss_history[-1])

import matplotlib.pyplot as plt
plt.plot(loss_history)
plt.xlabel("Iteration"); plt.ylabel("Loss")
plt.show()

from sklearn.metrics import mean_absolute_error, r2_score

pred_lakhs = np.expm1(np.asarray(X_test_final, dtype=float) @ w + b)
print("MAE:", mean_absolute_error(y_test, pred_lakhs))
print("R2:", r2_score(y_test, pred_lakhs))

