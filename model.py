loss_history = []

for i in range(n_iters):
    y_pred = X @ w + b
    error = y_pred - y

    loss = np.mean(error ** 2) + lam * np.sum(w ** 2)      # changed
    loss_history.append(loss)

    grad_w = (2 / n) * (X.T @ error) + 2 * lam * w         # changed
    grad_b = (2 / n) * np.sum(error)                       # bias: no penalty

    w -= lr * grad_w
    b -= lr * grad_b

pred_lakhs = np.expm1(np.asarray(X_test_final, dtype=float) @ w + b)
