#L1

X = np.asarray(X_train_final, dtype=float)
y = np.asarray(np.log1p(y_train), dtype=float)

n, d = X.shape
w = np.zeros(d)
b = 0.0
lr = 0.1
n_iters = 1000
lam = 0.01              # L1 penalty strength
loss_history = []

for i in range(n_iters):
    y_pred = X @ w + b
    error = y_pred - y

    loss = np.mean(error ** 2) + lam * np.sum(np.abs(w))
    loss_history.append(loss)

    grad_w = (2 / n) * (X.T @ error) + lam * np.sign(w)
    grad_b = (2 / n) * np.sum(error)

    w -= lr * grad_w
    b -= lr * grad_b

pred_lakhs = np.expm1(np.asarray(X_test_final, dtype=float) @ w + b)

print("MAE:", mean_absolute_error(y_test, pred_lakhs))
